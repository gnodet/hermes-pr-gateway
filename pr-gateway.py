# ---------------------------------------------------------------------------
# Registry
#
# Two-level structure (both protected by _registry_lock):
#
#   _listeners: { "repo#pr@route": { listener fields + per-listener state } }
#   _pr_state:  { "repo#pr":       { shared ETag + GitHub state for the PR } }
#
# The poller iterates unique PRs (from _pr_state), detects signals, then fans
# out to all matching listeners in _listeners.
# ---------------------------------------------------------------------------

_registry_lock = threading.Lock()
_listeners: dict[str, dict] = {}
_pr_state:  dict[str, dict] = {}

# Coalesce + serialisation per listener.
#
# Two-layer design:
#   1. Coalesce (trailing-edge timer, 15s): absorbs GitHub per-check_run floods.
#      Latest-wins per signal type within the window.
#   2. Serialisation (per-listener queue): only one agent runs at a time per
#      listener. While running, incoming signals accumulate in a pending map
#      (latest-wins per signal type; PUSHED supersedes CI_GREEN, etc.).
#      When the agent finishes (or times out after _AGENT_TIMEOUT_S), the pending
#      map is flushed and the next batch dispatched.
#
# Signal cancellation on merge into pending:
#   PUSHED   supersedes CI_GREEN and CI_FAILED  (new commit invalidates CI state)
#   CI_GREEN supersedes CI_FAILED               (latest CI result wins)
#   CI_FAILED supersedes CI_GREEN               (latest CI result wins)
#   All other signal types are kept independently.

_COALESCE_WINDOW_S = 15    # seconds to wait after last identical signal before dispatch
_AGENT_TIMEOUT_S   = 600   # pessimistic max agent runtime; listener unlocked after this

_pending_lock = threading.Lock()

# key: lkey  →  {"timer":      Timer|None,          # active coalesce timer
#                 "coalesce":   dict[signal→float],  # signals accumulating in window
#                 "pending":    dict[signal→float],  # signals queued while agent runs
#                 "running":    bool,
#                 "run_started": float|None}         # time.time() when agent started
_listener_queues: dict[str, dict] = {}


def _lq(lkey: str) -> dict:
    """Return (creating if needed) the queue state for a listener key."""
    if lkey not in _listener_queues:
        _listener_queues[lkey] = {
            "timer":       None,
            "coalesce":    {},
            "pending":     {},
            "running":     False,
            "run_started": None,
        }
    return _listener_queues[lkey]


def _merge_signal(target: dict, signal: str) -> None:
    """Merge a signal into a pending/coalesce map applying cancellation rules."""
    if signal == "PUSHED":
        target.pop("CI_GREEN",  None)
        target.pop("CI_FAILED", None)
    elif signal in ("CI_GREEN", "CI_FAILED"):
        target.pop("CI_GREEN",  None)
        target.pop("CI_FAILED", None)
    target[signal] = time.time()


def _dispatch_pending(lkey: str, listener: dict) -> None:
    """Fire accumulated pending signals for a listener (must be called with _pending_lock held)."""
    q = _listener_queues.get(lkey)
    if not q or not q["pending"]:
        return
    signals_to_send = list(q["pending"].keys())
    q["pending"].clear()
    q["running"]     = True
    q["run_started"] = time.time()
    threading.Thread(
        target=_run_and_drain, args=(lkey, listener, signals_to_send),
        daemon=True, name=f"dispatch-{lkey}",
    ).start()


def _run_and_drain(lkey: str, listener: dict, signals: list[str]) -> None:
    """Send signals to Hermes then check if more are waiting (runs in its own thread)."""
    repo_pr = f"{listener['repo']}#{listener['pr']}"
    for sig in signals:
        log.info("Dispatching %s → %s [%s]", sig, repo_pr, listener["route"])
        ok = notify_target(listener, sig)
        _record("dispatched", listener["repo"], listener["pr"], sig,
                route=listener["route"],
                result="ok" if ok else "error")
    with _pending_lock:
        q = _lq(lkey)
        q["running"]     = False
        q["run_started"] = None
        if q["pending"]:
            _dispatch_pending(lkey, listener)


def _listener_key(repo: str, pr: int, route: str) -> str:
    return f"{repo}#{pr}@{route}"


def _pr_key(repo: str, pr: int) -> str:
    return f"{repo}#{pr}"


def _pr_has_poll_listeners(pr_key: str) -> bool:
    """Return True if at least one poll-sourced listener exists for this PR.

    Includes direct listeners on this PR AND repo-level wildcard (pr=0) poll
    listeners — wildcards rely on the poller discovering and tracking real PRs.
    """
    prefix = pr_key + "@"
    repo = pr_key.split("#")[0]
    wildcard_prefix = _pr_key(repo, 0) + "@"
    return any(
        (k.startswith(prefix) or k.startswith(wildcard_prefix))
        and _listeners[k].get("source", "poll") == "poll"
        for k in _listeners
    )


def _pr_has_direct_listeners(pr_key: str) -> bool:
    """Return True if at least one non-wildcard listener is registered for this PR."""
    prefix = pr_key + "@"
    return any(k.startswith(prefix) for k in _listeners)


def _repos_with_poll_wildcard() -> set[str]:
    """Return the set of repos that have a wildcard (pr=0) poll listener."""
    repos = set()
    with _registry_lock:
        for k, v in _listeners.items():
            if v.get("pr") == 0 and v.get("source", "poll") == "poll":
                repos.add(v["repo"])
    return repos


def _check_repo_changed(repo: str, etag: str | None) -> tuple[bool, str | None]:
    """ETag-conditional GET on the repo resource itself.

    Returns (changed, new_etag).
    - (False, None)      — 304, repo unchanged, skip PR list fetch
    - (True,  new_etag)  — 200, something changed, fetch PR list
    - (True,  None)      — error, fetch PR list to be safe
    """
    try:
        status, _, new_etag = gh_get(f"repos/{repo}", etag=etag)
        if status == 304:
            return False, None
        return True, new_etag
    except Exception as e:
        log.warning("Failed to check repo %s: %s", repo, e)
        return True, None  # err on the side of discovery


def _discover_open_prs(repo: str) -> list[int]:
    """Fetch the list of open PR numbers for a repo. Returns [] on error."""
    try:
        status, data, _ = gh_get(
            f"repos/{repo}/pulls?state=open&per_page=100",
        )
        if status in (200, 201) and isinstance(data, list):
            return [pr["number"] for pr in data if isinstance(pr, dict) and "number" in pr]
    except Exception as e:
        log.warning("Failed to discover PRs for %s: %s", repo, e)
    return []


def _pr_has_listeners(pr_key: str) -> bool:
    """Return True if at least one listener (any source) exists for this PR."""
    prefix = pr_key + "@"
    return any(k.startswith(prefix) for k in _listeners)


def load_registry() -> None:
    global _listeners, _pr_state
    if not REGISTRY_FILE.exists():
        return
    try:
        with open(REGISTRY_FILE) as f:
            data = json.load(f)
        with _registry_lock:
            _listeners = data.get("listeners", {})
            _pr_state  = data.get("pr_state", {})
        log.info("Loaded %d listener(s) for %d PR(s)",
                 len(_listeners), len(_pr_state))
    except Exception as e:
        log.error("Failed to load registry: %s", e)


def save_registry() -> None:
    tmp = REGISTRY_FILE.with_suffix(".tmp")
    try:
        with _registry_lock:
            data = {"listeners": dict(_listeners), "pr_state": dict(_pr_state)}
        with open(tmp, "w") as f:
            json.dump(data, f, indent=2)
        tmp.replace(REGISTRY_FILE)
    except Exception as e:
        log.error("Failed to save registry: %s", e)


def add_watch(entry: dict) -> tuple[bool, str]:
    repo  = entry.get("repo", "").strip()
    pr    = entry.get("pr")
    route = entry.get("route", "babysit-pr").strip()

    if not repo or pr is None:
        return False, "repo and pr are required"
    try:
        pr = int(pr)
    except (TypeError, ValueError):
        return False, "pr must be an integer"
    if pr < 0:
        return False, "pr must be a non-negative integer (0 = wildcard)"
    if not re.match(r"^[a-zA-Z0-9_.-]+/[a-zA-Z0-9_.-]+$", repo):
        return False, "repo must be in owner/repo format"
    if not re.match(r"^[a-zA-Z0-9_-]+$", route):
        return False, "route must be alphanumeric/hyphens/underscores"

    raw_signals = entry.get("signals", ["*"])
    if raw_signals == ["*"] or "*" in raw_signals:
        signals = ["*"]
    else:
        invalid = set(raw_signals) - ALL_SIGNALS
        if invalid:
            return False, f"Unknown signals: {invalid}. Valid: {ALL_SIGNALS}"
        signals = list(raw_signals)

    # source: "poll" (default, apache/*) or "webhook" (maveniverse/*, jline/*)
    source = entry.get("source", "poll").strip()
    if source not in ("poll", "webhook"):
        return False, "source must be 'poll' or 'webhook'"

    # Wildcard (pr=0) with source=poll: the poller will discover open PRs for this
    # repo and poll them individually. source=webhook is still recommended when
    # admin access is available (lower latency, zero polling cost).
    # No validation error — both combinations are supported.

    lkey  = _listener_key(repo, pr, route)
    prkey = _pr_key(repo, pr)
    now   = time.time()

    listener = {
        "repo":     repo,
        "pr":       pr,
        "route":    route,
        "signals":  signals,
        "source":   source,
        "branch":   entry.get("branch", ""),
        "worktree": entry.get("worktree", ""),
        "deliver":  entry.get("deliver", "origin"),
        "added_at": now,
        # per-listener state
        "_last_signal": None,
        "_last_fired":  None,
    }

    with _registry_lock:
        existed = lkey in _listeners
        _listeners[lkey] = listener
        # Initialise PR state for non-wildcard listeners only
        # (wildcards have no per-PR state — they piggyback on webhook dispatch)
        if pr != 0 and prkey not in _pr_state:
            _pr_state[prkey] = {
                "repo":        repo,
                "pr":          pr,
                "_etag":       None,
                "_head_sha":   None,
                "_ci_status":  None,
                "_updated_at": None,
                "_last_polled": None,
            }

    save_registry()
    action = "Updated" if existed else "Registered"
    sig_desc = "*" if signals == ["*"] else ",".join(signals)
    pr_desc  = "wildcard" if pr == 0 else str(pr)
    log.info("%s listener: %s (pr=%s, signals=%s)", action, lkey, pr_desc, sig_desc)
    return True, f"{action} listener {lkey} (signals={sig_desc})"


def remove_watch(repo: str, pr: int, route: Optional[str] = None) -> tuple[bool, str]:
    """
    Remove listener(s). If route is given, remove only that listener.
    Otherwise remove all listeners for the PR (and its PR state).
    """
    prkey = _pr_key(repo, pr)

    with _registry_lock:
        if route:
            lkey = _listener_key(repo, pr, route)
            if lkey not in _listeners:
                return False, f"No listener found for {lkey}"
            del _listeners[lkey]
            # Clean up PR state if no listeners remain
            if not _pr_has_listeners(prkey):
                _pr_state.pop(prkey, None)
            removed = [lkey]
        else:
            # Remove all listeners for this PR
            to_remove = [k for k in _listeners if k.startswith(prkey + "@")]
            if not to_remove:
                return False, f"No listeners found for {prkey}"
            for k in to_remove:
                del _listeners[k]
            _pr_state.pop(prkey, None)
            removed = to_remove

    save_registry()
    for k in removed:
        log.info("Removed listener: %s", k)
    return True, f"Removed {len(removed)} listener(s): {', '.join(removed)}"


def list_watches() -> list[dict]:
    with _registry_lock:
        return [
            {k: v for k, v in entry.items() if not k.startswith("_")}
            for entry in _listeners.values()
        ]


def _get_pr_state_snapshot() -> dict[str, dict]:
    """Return a copy of pr_state for the poller."""
    with _registry_lock:
        return {k: dict(v) for k, v in _pr_state.items()}


def _get_listeners_for_pr(prkey: str) -> list[dict]:
    """Return copies of all listeners for a given PR key, plus repo-level wildcards (pr=0)."""
    # Extract repo from "repo#pr" key
    repo = prkey.split("#")[0]
    wildcard_prefix = _pr_key(repo, 0) + "@"
    with _registry_lock:
        return [
            dict(v) for k, v in _listeners.items()
            if k.startswith(prkey + "@") or k.startswith(wildcard_prefix)
        ]


def _update_pr_state(prkey: str, **kwargs) -> None:
    with _registry_lock:
        if prkey in _pr_state:
            _pr_state[prkey].update(kwargs)


def _update_listener_state(lkey: str, **kwargs) -> None:
    with _registry_lock:
        if lkey in _listeners:
            _listeners[lkey].update(kwargs)


