def gh_token() -> str:
    if GH_TOKEN_FILE.exists():
        return GH_TOKEN_FILE.read_text().strip()
    return os.environ.get("GH_TOKEN", "")


def gh_get(path: str, etag: Optional[str] = None) -> tuple[int, dict | list | None, str | None]:
    url = f"{GITHUB_API}/{path.lstrip('/')}"
    headers = {
        "Authorization":        f"token {gh_token()}",
        "Accept":               "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    if etag:
        headers["If-None-Match"] = etag
    try:
        req = Request(url, headers=headers)
        with urlopen(req, timeout=20) as resp:
            new_etag = resp.headers.get("ETag")
            body = json.loads(resp.read().decode())
            return resp.status, body, new_etag
    except HTTPError as e:
        if e.code == 304:
            return 304, None, None
        log.warning("GitHub API %s → %d", path, e.code)
        return e.code, None, None
    except (URLError, Exception) as e:
        log.warning("GitHub API %s → %s", path, e)
        return 0, None, None


def get_pr_snapshot(repo: str, pr: int) -> Optional[dict]:
    status, body, _ = gh_get(f"repos/{repo}/pulls/{pr}")
    if status == 200 and body:
        return {
            "state":      body.get("state"),
            "merged":     body.get("merged", False),
            "draft":      body.get("draft", False),
            "head_sha":   body.get("head", {}).get("sha"),
            "updated_at": body.get("updated_at"),
        }
    return None


def get_ci_status(repo: str, sha: str) -> str:
    status, body, _ = gh_get(f"repos/{repo}/commits/{sha}/check-runs")
    if status == 200 and body:
        runs = body.get("check_runs", [])
        if not runs:
            return "no_checks"
        conclusions = [r.get("conclusion") or "pending" for r in runs]
        if any(c == "failure" for c in conclusions):
            return "failure"
        if all(c == "success" for c in conclusions):
            return "success"
        return "pending"
    # Fallback: commit statuses
    status, body, _ = gh_get(f"repos/{repo}/commits/{sha}/status")
    if status == 200 and body:
        return body.get("state", "unknown")
    return "unknown"


# ---------------------------------------------------------------------------
# Hermes webhook callback
# ---------------------------------------------------------------------------

def _hmac_signature(secret: str, body: bytes) -> str:
    return "sha256=" + hmac.new(secret.encode(), body, hashlib.sha256).hexdigest()


def notify_target(listener: dict, signal: str) -> bool:
    """POST a signal to the Hermes webhook adapter for a specific route."""
    # Parse deliver field: "slack:C0BUUAYDQA1" → deliver_chat_id="C0BUUAYDQA1"
    # For Hermes webhook routes, deliver/deliver_extra are now handled natively in config.yaml.
    # We pass deliver_chat_id so the {deliver_chat_id} template in deliver_extra resolves correctly.
    raw_deliver = listener.get("deliver", "origin")
    if ":" in raw_deliver:
        _, deliver_chat_id = raw_deliver.split(":", 1)
    else:
        deliver_chat_id = raw_deliver

    payload = {
        "source":         "pr-gateway",
        "signal":         signal,
        "repo":           listener["repo"],
        "pr":             listener["pr"],
        "branch":         listener.get("branch", ""),
        "worktree":       listener.get("worktree", ""),
        "deliver_chat_id": deliver_chat_id,
    }
    body = json.dumps(payload).encode()
    sig  = _hmac_signature(WEBHOOK_SECRET, body)
    route = listener["route"]
    url  = f"{TARGET_URL}/webhooks/{route}"

    try:
        req = Request(
            url,
            data=body,
            headers={
                "Content-Type":        "application/json",
                "X-Hub-Signature-256": sig,
                "X-GitHub-Event":      "pr_gateway",
            },
            method="POST",
        )
        with urlopen(req, timeout=10) as resp:
            log.info("Dispatched [%s]: %s#%s → %s (HTTP %d)",
                     route, listener["repo"], listener["pr"], signal, resp.status)
            return True
    except Exception as e:
        log.error("Failed to dispatch [%s] for %s#%s: %s",
                  route, listener["repo"], listener["pr"], e)
        return False


