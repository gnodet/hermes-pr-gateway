def _read_body(handler: BaseHTTPRequestHandler) -> Optional[dict]:
    length = int(handler.headers.get("Content-Length", 0))
    if not length:
        return {}
    try:
        return json.loads(handler.rfile.read(length))
    except json.JSONDecodeError:
        return None


def _parse_watch_path(path: str) -> Optional[tuple[str, int, Optional[str]]]:
    """
    Parse DELETE path variants:
      /watch/{owner%2Frepo}/{pr}
      /watch/{owner%2Frepo}/{pr}/{route}
      /watch/{owner}/{repo}/{pr}
      /watch/{owner}/{repo}/{pr}/{route}
    Returns (repo, pr, route_or_None) or None on parse failure.
    """
    # URL-decode the path first so %2F becomes /
    path = unquote(path)
    parts = path.lstrip("/").split("/")
    # parts[0] == "watch", rest are segments
    if not parts or parts[0] != "watch":
        return None
    rest = parts[1:]

    # Now after unquoting, "apache/camel" would have been split already.
    # Possible shapes:
    #   ["owner", "repo", "pr"]           → 3 parts
    #   ["owner", "repo", "pr", "route"]  → 4 parts
    # (The %2F case is now indistinguishable from the / case after unquoting.)
    if len(rest) == 2:
        # /watch/owner%2Frepo/pr — but after unquote owner/repo gets split
        # So this can't happen for the encoded case; only if repo had no slash
        return None
    elif len(rest) == 3:
        repo  = f"{rest[0]}/{rest[1]}"
        pr_s  = rest[2]
        route = None
    elif len(rest) == 4:
        repo  = f"{rest[0]}/{rest[1]}"
        pr_s  = rest[2]
        route = rest[3]
    else:
        return None

    try:
        pr = int(pr_s)
    except ValueError:
        return None
    return repo, pr, route


class GatewayHandler(BaseHTTPRequestHandler):
    def log_message(self, fmt, *args):
        log.debug("HTTP: " + fmt, *args)

    def do_GET(self):
        path = urlparse(self.path).path.rstrip("/")

        if path == "/health":
            with _registry_lock:
                n_listeners = len(_listeners)
                n_prs       = len(_pr_state)
            _json_response(self, 200, {
                "status": "ok", "listeners": n_listeners, "prs": n_prs,
            })

        elif path == "/watches":
            _json_response(self, 200, list_watches())

        elif path == "/history":
            _json_response(self, 200, _get_history())

        elif path in ("/ui", ""):
            _html_response(self, 200, _render_dashboard())

        else:
            _json_response(self, 404, {"error": "not found"})

    def do_POST(self):
        path = urlparse(self.path).path.rstrip("/")

        if path == "/watch":
            body = _read_body(self)
            if body is None:
                _json_response(self, 400, {"error": "invalid JSON"})
                return
            ok, msg = add_watch(body)
            _json_response(self, 200 if ok else 400, {"ok": ok, "message": msg})

        elif path == "/fire":
            # POST {"repo": "owner/repo", "pr": 174, "signal": "PUSHED"}
            # Injects a signal directly into the dispatch pipeline — no GitHub webhook needed.
            body = _read_body(self)
            if body is None:
                _json_response(self, 400, {"error": "invalid JSON"})
                return
            repo   = body.get("repo", "").strip()
            pr_raw = body.get("pr")
            signal = body.get("signal", "").strip().upper()
            if not repo or pr_raw is None or not signal:
                _json_response(self, 400, {"error": "repo, pr and signal are required"})
                return
            try:
                pr = int(pr_raw)
            except (TypeError, ValueError):
                _json_response(self, 400, {"error": "pr must be an integer"})
                return
            if signal not in ALL_SIGNALS:
                _json_response(self, 400, {
                    "error": f"Unknown signal '{signal}'. Valid: {sorted(ALL_SIGNALS)}"
                })
                return
            prkey = _pr_key(repo, pr)
            listeners = _get_listeners_for_pr(prkey)
            if not listeners:
                _json_response(self, 404, {"error": f"No listeners for {prkey}"})
                return
            log.info("Manual /fire: %s → %s", signal, prkey)
            _dispatch_signals(prkey, [signal])
            _json_response(self, 200, {
                "ok": True,
                "message": f"Fired {signal} → {prkey} ({len(listeners)} listener(s))",
            })

        elif path == "/repo-secret":
            # POST {"repo": "owner/repo", "secret": "..."}
            body = _read_body(self)
            if body is None:
                _json_response(self, 400, {"error": "invalid JSON"})
                return
            repo   = body.get("repo", "").strip()
            secret = body.get("secret", "").strip()
            if not repo or not secret:
                _json_response(self, 400, {"error": "repo and secret are required"})
                return
            set_repo_secret(repo, secret)
            log.info("Set webhook secret for %s", repo)
            _json_response(self, 200, {"ok": True, "message": f"Secret set for {repo}"})

        else:
            _json_response(self, 404, {"error": "not found"})

    def do_DELETE(self):
        path = urlparse(self.path).path.rstrip("/")
        parsed = _parse_watch_path(path)
        if not parsed:
            _json_response(self, 404, {"error": "not found"})
            return

        repo, pr, route = parsed
        ok, msg = remove_watch(repo, pr, route)
        _json_response(self, 200 if ok else 404, {"ok": ok, "message": msg})


def api_server() -> None:
    server = HTTPServer(("0.0.0.0", API_PORT), GatewayHandler)
    log.info("API server listening on http://0.0.0.0:%d  (LAN accessible)", API_PORT)
    server.serve_forever()


