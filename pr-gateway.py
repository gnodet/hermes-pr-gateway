def _signals_match(listener: dict, signal: str) -> bool:
    sigs = listener.get("signals", ["*"])
    return "*" in sigs or signal in sigs


def _poll_pr(prkey: str, state: dict) -> list[str]:
    """
    Poll one PR. Returns the list of signals detected (may be empty).
    Updates _pr_state in place (via _update_pr_state).
    """
    repo = state["repo"]
    pr   = state["pr"]

    # ETag-conditional poll on timeline (304 = free)
    status, _, new_etag = gh_get(
        f"repos/{repo}/issues/{pr}/timeline?per_page=5",
        etag=state.get("_etag"),
    )
    if new_etag:
        _update_pr_state(prkey, _etag=new_etag, _last_polled=time.time())

    if status == 304:
        return []  # nothing changed

    if status not in (200, 201):
        log.warning("Unexpected status %d polling %s", status, prkey)
        return []

    # Something changed — fetch full PR state
    snapshot = get_pr_snapshot(repo, pr)
    if not snapshot:
        log.warning("Could not fetch PR snapshot for %s", prkey)
        return []

    prev_sha     = state.get("_head_sha")
    prev_ci      = state.get("_ci_status")
    prev_updated = state.get("_updated_at")
    cur_sha      = snapshot["head_sha"]
    cur_updated  = snapshot["updated_at"]

    # First time seeing this PR — initialise, emit nothing
    if prev_sha is None:
        cur_ci = get_ci_status(repo, cur_sha)
        _update_pr_state(prkey,
            _head_sha=cur_sha, _ci_status=cur_ci, _updated_at=cur_updated)
        log.info("Initialised state for %s (sha=%.8s, ci=%s)", prkey, cur_sha, cur_ci)
        return []

    signals = []

    if snapshot["merged"]:
        signals.append("MERGED")
    elif snapshot["state"] == "closed":
        signals.append("CLOSED")
    else:
        if cur_sha != prev_sha:
            signals.append("PUSHED")

        cur_ci = get_ci_status(repo, cur_sha)
        if cur_ci == "failure" and prev_ci != "failure":
            signals.append("CI_FAILED")
        elif cur_ci == "success" and (prev_ci != "success" or cur_sha != prev_sha):
            signals.append("CI_GREEN")

        if prev_updated and cur_updated != prev_updated and cur_sha == prev_sha:
            signals.append("NEW_COMMENTS")

        _update_pr_state(prkey,
            _head_sha=cur_sha, _ci_status=cur_ci, _updated_at=cur_updated)

    return signals


def _dispatch_signals(prkey: str, signals: list[str]) -> None:
    """Fan out detected signals to all matching listeners for this PR."""
    if not signals:
        return

    # Extract real PR number from prkey for passing to wildcard listeners
    repo, pr_str = prkey.split("#")
    real_pr = int(pr_str)

    listeners = _get_listeners_for_pr(prkey)
    terminal  = any(s in ("MERGED", "CLOSED") for s in signals)

    for listener in listeners:
        is_wildcard = listener["pr"] == 0
        route = listener["route"]
        lkey  = _listener_key(listener["repo"], listener["pr"], route)

        # Find the first signal this listener cares about
        matched = next((s for s in signals if _signals_match(listener, s)), None)
        if not matched:
            continue

        # For wildcard listeners, inject the real PR number so the agent knows which PR fired
        effective_listener = listener
        if is_wildcard:
            effective_listener = dict(listener)
            effective_listener["pr"] = real_pr

        # Record that this listener received the signal (entering coalesce window)
        _record("coalesced", listener["repo"], effective_listener["pr"], matched,
                route=route, result="coalescing",
                detail=f"window={_COALESCE_WINDOW_S}s")

        # --- Layer 1: coalesce trailing-edge timer ---
        # Re-arm the timer on every incoming signal of the same type.
        # When it expires quietly (no duplicate within _COALESCE_WINDOW_S),
        # we promote the coalesced signals to the serialisation layer.
        with _pending_lock:
            q = _lq(lkey)

            # Merge into coalesce window (latest-wins + cancellation rules)
            _merge_signal(q["coalesce"], matched)

            # Cancel existing timer and re-arm
            if q["timer"] is not None:
                q["timer"].cancel()

            def _coalesce_expired(k=lkey, lst=effective_listener):
                with _pending_lock:
                    q2 = _lq(k)
                    q2["timer"] = None
                    if not q2["coalesce"]:
                        return

                    # Check timeout: if running but agent has exceeded _AGENT_TIMEOUT_S, unlock
                    if q2["running"] and q2["run_started"] is not None:
                        if time.time() - q2["run_started"] > _AGENT_TIMEOUT_S:
                            log.warning("Agent timeout for %s — unlocking listener", k)
                            q2["running"]     = False
                            q2["run_started"] = None

                    # Merge coalesced signals into pending (with cancellation rules)
                    for sig in q2["coalesce"]:
                        _merge_signal(q2["pending"], sig)
                    q2["coalesce"].clear()

                    # --- Layer 2: serialisation ---
                    if not q2["running"]:
                        _dispatch_pending(k, lst)
                    else:
                        log.debug("Agent busy for %s — %d signal(s) queued: %s",
                                  k, len(q2["pending"]), list(q2["pending"]))
                        for sig in q2["pending"]:
                            _record("skipped", lst["repo"], lst["pr"], sig,
                                    route=lst["route"], result="busy",
                                    detail="agent running, signal queued")

            t = threading.Timer(_COALESCE_WINDOW_S, _coalesce_expired)
            t.daemon = True
            q["timer"] = t
            t.start()

    # Terminal signals — remove non-wildcard listeners for this PR only
    if terminal:
        remove_watch(repo, real_pr)


def poller_loop() -> None:
    log.info("Poller started (interval=%ds)", POLL_INTERVAL)
    # Per-repo discovery state: {repo: {"ts": float, "etag": str|None}}
    _repo_disc: dict[str, dict] = {}
    DISCOVERY_INTERVAL = 120  # check repo ETag every 2 minutes

    while True:
        # --- Repo-level discovery for poll wildcards ---
        # Gate: ETag-conditional GET on the repo itself (1 cheap call per repo).
        # Only fetch the open PR list when the repo ETag changes (200 vs 304).
        poll_wildcard_repos = _repos_with_poll_wildcard()
        now = time.time()
        for repo in poll_wildcard_repos:
            disc = _repo_disc.setdefault(repo, {"ts": 0, "etag": None})
            if now - disc["ts"] < DISCOVERY_INTERVAL:
                continue

            changed, new_etag = _check_repo_changed(repo, disc["etag"])
            disc["ts"] = time.time()
            if new_etag:
                disc["etag"] = new_etag

            if not changed:
                log.debug("Repo %s unchanged (304) — skipping PR discovery", repo)
                continue

            pr_numbers = _discover_open_prs(repo)
            log.info("Discovered %d open PRs for %s: %s", len(pr_numbers), repo,
                     pr_numbers[:10])
            with _registry_lock:
                open_set = set(pr_numbers)
                for pr_num in pr_numbers:
                    prkey = _pr_key(repo, pr_num)
                    if prkey not in _pr_state:
                        _pr_state[prkey] = {
                            "repo":         repo,
                            "pr":           pr_num,
                            "_etag":        None,
                            "_head_sha":    None,
                            "_ci_status":   None,
                            "_updated_at":  None,
                            "_last_polled": None,
                        }
                        log.info("Auto-registered PR state for %s#%d (wildcard poll)",
                                 repo, pr_num)

                # Purge _pr_state entries for PRs no longer open and with
                # no direct (non-wildcard) listeners — closed/merged during a gap.
                stale = [
                    pk for pk in list(_pr_state)
                    if _pr_state[pk]["repo"] == repo
                    and _pr_state[pk]["pr"] not in open_set
                    and not _pr_has_direct_listeners(pk)
                ]
                for pk in stale:
                    del _pr_state[pk]
                    log.info("Purged stale PR state for %s (no longer open)", pk)


        # --- Poll registered PRs ---
        pr_states = _get_pr_state_snapshot()

        if not pr_states:
            time.sleep(POLL_INTERVAL)
            continue

        for prkey, state in pr_states.items():
            # Skip if no poll-sourced listeners remain (webhook-only PRs don't need polling)
            with _registry_lock:
                if not _pr_has_poll_listeners(prkey):
                    continue

            try:
                signals = _poll_pr(prkey, state)
                if signals:
                    repo, pr_str = prkey.split("#")
                    for sig in signals:
                        _record("poll_signal", repo, int(pr_str), sig, detail="poller")
                _dispatch_signals(prkey, signals)
            except Exception as e:
                log.error("Error polling %s: %s", prkey, e, exc_info=True)

            time.sleep(2)  # small gap between PRs

        time.sleep(POLL_INTERVAL)


