#!/usr/bin/env python3
"""
pr-gateway — Event-driven PR watcher daemon.

HTTP API (default :8645):
  POST   /watch                        Register a PR listener
  DELETE /watch/{repo}/{pr}            Remove all listeners for a PR
  DELETE /watch/{repo}/{pr}/{route}    Remove one specific listener
  GET    /watches                      List active listeners
  GET    /health                       Health check

Each registration specifies:
  - repo:     "owner/repo"
  - pr:       PR number, or 0 for a repo-level wildcard (source=webhook only)
  - route:    Hermes webhook route to call (e.g. "babysit-pr", "review-loop")
  - signals:  list of signals to forward, or ["*"] for all
              (PUSHED, OPENED, MERGED, CLOSED, DRAFT,
               CI_GREEN, CI_FAILED, CI_CANCELLED,
               NEW_COMMENTS, APPROVED, CHANGES_REQUESTED,
               REVIEW_REQUESTED, LABELED)
  - branch:   branch name (forwarded to agent)
  - worktree: local worktree path (forwarded to agent)
  - deliver:  Hermes delivery target (forwarded to agent)

The same PR can have multiple listeners with different routes/signals.
Registry key: "{repo}#{pr}@{route}"

Wildcard listeners (pr=0):
  Registered with source=webhook and pr=0, they receive events for ALL PRs on
  a repo. Useful for repo-level automation (e.g. review-loop) that should fire
  on any new push without knowing PR numbers in advance. Wildcard listeners are
  never auto-removed on MERGED/CLOSED (they survive across all PRs).

ETag state is shared across listeners for the same PR (one poll per PR,
dispatched to N listeners based on their signal filters).

Registry is persisted to REGISTRY_FILE for crash recovery.
"""

