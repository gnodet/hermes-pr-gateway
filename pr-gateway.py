def main() -> None:
    log.info("pr-gateway starting (api=%d internal, gh-webhook=%d public, hermes=%s)",
             API_PORT, GH_PORT, TARGET_URL)
    PID_FILE.write_text(str(os.getpid()))
    load_registry()
    _load_secrets_from_env()

    # Poller thread
    threading.Thread(target=poller_loop, name="poller", daemon=True).start()

    # GitHub webhook receiver thread (public)
    threading.Thread(target=gh_webhook_server, name="gh-webhook", daemon=True).start()

    # Admin API in main thread (internal only, blocks)
    try:
        api_server()
    except KeyboardInterrupt:
        log.info("Shutting down.")
    finally:
        PID_FILE.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
