# Map GitHub event+action combos to our signal vocabulary
def _gh_event_to_signals(event: str, payload: dict) -> list[str]:
    """
    Translate a GitHub webhook event+payload into pr-gateway signal(s).
    Returns an empty list if the event is not actionable.
    """
    signals = []
    action  = payload.get("action", "")

    if event == "pull_request":
        if action == "synchronize":
            signals.append("PUSHED")
        elif action in ("opened", "reopened", "ready_for_review"):
            signals.append("OPENED")
        elif action == "closed":
            if payload.get("pull_request", {}).get("merged"):
                signals.append("MERGED")
            else:
                signals.append("CLOSED")
        elif action == "review_requested":
            signals.append("REVIEW_REQUESTED")
        elif action in ("labeled", "unlabeled"):
            signals.append("LABELED")
        elif action in ("converted_to_draft",):
            signals.append("DRAFT")

    elif event == "check_run":
        if action == "completed":
            conclusion = payload.get("check_run", {}).get("conclusion")
            if conclusion == "success":
                signals.append("CI_GREEN")
            elif conclusion in ("failure", "action_required", "timed_out"):
                signals.append("CI_FAILED")
            elif conclusion in ("cancelled", "skipped", "neutral"):
                signals.append("CI_CANCELLED")

    elif event == "check_suite":
        if action == "completed":
            conclusion = payload.get("check_suite", {}).get("conclusion")
            if conclusion == "success":
                signals.append("CI_GREEN")
            elif conclusion in ("failure", "action_required", "timed_out"):
                signals.append("CI_FAILED")
            elif conclusion in ("cancelled", "skipped", "neutral"):
                signals.append("CI_CANCELLED")

    elif event == "pull_request_review":
        state = payload.get("review", {}).get("state", "")
        if action == "submitted":
            if state == "approved":
                signals.append("APPROVED")
            elif state == "changes_requested":
                signals.append("CHANGES_REQUESTED")
            else:
                # Suppress NEW_COMMENTS for bot-generated reviews (anti-loop filter)
                body = payload.get("review", {}).get("body", "") or ""
                if _BOT_WATERMARK not in body:
                    signals.append("NEW_COMMENTS")
        elif action == "dismissed":
            signals.append("NEW_COMMENTS")

    elif event in ("issue_comment", "pull_request_review_comment"):
        # issue_comment: PR comments (GitHub treats them as issue comments)
        # pull_request_review_comment: inline diff comments
        is_pr = (
            "pull_request" in payload.get("issue", {}).get("html_url", "")
            or "pull_request" in payload  # pull_request_review_comment always has it
        )
        if is_pr and action in ("created", "edited"):
            # Suppress NEW_COMMENTS for bot-generated comments (anti-loop filter).
            # The bot watermarks every comment/review it posts; if the body contains
            # that string, the event is our own output and must not re-trigger us.
            comment_body = (
                payload.get("comment", {}).get("body", "")
                or payload.get("review", {}).get("body", "")
                or ""
            )
            if _BOT_WATERMARK not in comment_body:
                signals.append("NEW_COMMENTS")

    elif event == "workflow_run":
        if action == "completed":
            conclusion = payload.get("workflow_run", {}).get("conclusion")
            if conclusion == "success":
                signals.append("CI_GREEN")
            elif conclusion in ("failure", "timed_out", "action_required"):
                signals.append("CI_FAILED")
            elif conclusion in ("cancelled", "skipped", "neutral"):
                signals.append("CI_CANCELLED")

    elif event == "status":
        # Legacy commit status API
        state = payload.get("state", "")
        if state == "success":
            signals.append("CI_GREEN")
        elif state in ("failure", "error"):
            signals.append("CI_FAILED")

    return signals


def _verify_gh_signature(secret: str, body: bytes, sig_header: str) -> bool:
    if not sig_header or not sig_header.startswith("sha256="):
        return False
    expected = "sha256=" + hmac.new(secret.encode(), body, hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected, sig_header)


class GitHubWebhookHandler(BaseHTTPRequestHandler):
    """Handles inbound GitHub webhook events on the public port."""

    def log_message(self, fmt, *args):
        log.debug("GH-webhook: " + fmt, *args)

    def do_POST(self):
        # Path: /github/{owner}/{repo}
        path  = urlparse(self.path).path.rstrip("/")
        parts = path.lstrip("/").split("/")
        # parts: ["github", "owner", "repo"]
        if len(parts) != 3 or parts[0] != "github":
            self._respond(404, {"error": "not found"})
            return

        repo = f"{parts[1]}/{parts[2]}"

        # Read body
        length = int(self.headers.get("Content-Length", 0))
        body   = self.rfile.read(length) if length else b""

        # Validate HMAC — use per-repo secret if configured, else WEBHOOK_SECRET
        sig    = self.headers.get("X-Hub-Signature-256", "")
        secret = _repo_webhook_secret(repo)
        if not _verify_gh_signature(secret, body, sig):
            log.warning("Invalid GitHub signature for %s", repo)
            self._respond(403, {"error": "invalid signature"})
            return

        event = self.headers.get("X-GitHub-Event", "")
        try:
            payload = json.loads(body)
        except json.JSONDecodeError:
            self._respond(400, {"error": "invalid JSON"})
            return

        # Extract PR number from payload
        pr_num = _extract_pr_number(event, payload)
        if pr_num is None:
            # Not a PR-related event we care about — ack and ignore
            self._respond(200, {"ok": True, "message": "ignored"})
            return

        prkey   = _pr_key(repo, pr_num)
        signals = _gh_event_to_signals(event, payload)

        if not signals:
            self._respond(200, {"ok": True, "message": "no actionable signal"})
            return

        log.info("GitHub webhook: %s/%s#%d event=%s → %s",
                 repo, "", pr_num, event, signals)

        # Record inbound webhook event
        for sig in signals:
            _record("webhook_received", repo, pr_num, sig, detail=f"event={event}")

        # Update shared PR state from payload where possible
        _update_pr_state_from_gh(prkey, event, payload)

        # Dispatch to listeners
        _dispatch_signals(prkey, signals)

        self._respond(200, {"ok": True, "signals": signals})

    def do_GET(self):
        path = urlparse(self.path).path.rstrip("/")
        if path == "/health":
            self._respond(200, {"status": "ok", "port": "github-webhook"})
        else:
            self._respond(404, {"error": "not found"})

    def _respond(self, code: int, data: dict) -> None:
        body = json.dumps(data).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


def _extract_pr_number(event: str, payload: dict) -> Optional[int]:
    """Extract the PR number from a GitHub webhook payload."""
    if event == "pull_request":
        return payload.get("pull_request", {}).get("number")
    elif event in ("check_run", "check_suite"):
        # check_run.pull_requests is a list
        prs = payload.get(event.replace("_", "_"), {}).get("pull_requests", [])
        if prs:
            return prs[0].get("number")
        # check_suite may not have PR list — skip
        return None
    elif event == "pull_request_review":
        return payload.get("pull_request", {}).get("number")
    elif event == "issue_comment":
        # Only applicable if it's a PR
        issue = payload.get("issue", {})
        if "pull_request" in issue:
            return issue.get("number")
    return None


def _update_pr_state_from_gh(prkey: str, event: str, payload: dict) -> None:
    """Update cached PR state from the webhook payload where possible."""
    if event == "pull_request":
        pr = payload.get("pull_request", {})
        _update_pr_state(prkey,
            _head_sha=pr.get("head", {}).get("sha"),
            _updated_at=pr.get("updated_at"),
        )


# Per-repo webhook secrets — stored in the registry or defaulting to WEBHOOK_SECRET
_repo_secrets: dict[str, str] = {}
_repo_secrets_lock = threading.Lock()


def set_repo_secret(repo: str, secret: str) -> None:
    with _repo_secrets_lock:
        _repo_secrets[repo] = secret


def _repo_webhook_secret(repo: str) -> str:
    with _repo_secrets_lock:
        return _repo_secrets.get(repo, WEBHOOK_SECRET)


def _load_secrets_from_env() -> None:
    """
    Read WEBHOOK_SECRET_<owner>__<repo> env vars at startup and populate
    the per-repo secret table. Double underscore separates owner from repo.
    Hyphens in names are stored as underscores in the env var name;
    we try both the literal form and the hyphen-restored form.
    """
    prefix = "WEBHOOK_SECRET_"
    for key, val in os.environ.items():
        if key.startswith(prefix) and val:
            repo_raw = key[len(prefix):]
            if "__" not in repo_raw:
                continue
            owner_part, repo_part = repo_raw.split("__", 1)
            # Env vars can't contain hyphens — stored as underscores.
            # Store both forms so we match regardless of whether the repo
            # name has underscores or hyphens.
            for repo in (
                f"{owner_part}/{repo_part}",                          # literal (underscores)
                f"{owner_part}/{repo_part.replace('_', '-')}",        # hyphens restored
            ):
                _repo_secrets[repo] = val
            log.info("Loaded webhook secret for %s (from env)", f"{owner_part}/{repo_part}")


def gh_webhook_server() -> None:
    server = HTTPServer(("0.0.0.0", GH_PORT), GitHubWebhookHandler)
    log.info("GitHub webhook receiver on http://0.0.0.0:%d  (public)", GH_PORT)
    server.serve_forever()


