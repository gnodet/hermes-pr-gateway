# ---------------------------------------------------------------------------
# Event history — in-memory ring buffer (500 entries, never persisted)
# ---------------------------------------------------------------------------

import collections as _collections

_HISTORY_MAXLEN = 500
_history: _collections.deque = _collections.deque(maxlen=_HISTORY_MAXLEN)
_history_lock = threading.Lock()


def _record(kind: str, repo: str, pr: int, signal: str,
            route: str = "", result: str = "ok", detail: str = "") -> None:
    """Append one event to the in-memory history ring buffer."""
    entry = {
        "ts":     time.time(),
        "kind":   kind,    # webhook_received | poll_signal | dispatched | skipped | coalesced
        "repo":   repo,
        "pr":     pr,
        "signal": signal,
        "route":  route,
        "result": result,  # ok | skipped | error | coalesced | busy
        "detail": detail,
    }
    with _history_lock:
        _history.append(entry)


def _get_history() -> list[dict]:
    with _history_lock:
        return list(reversed(_history))  # newest first

